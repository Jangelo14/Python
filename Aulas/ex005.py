#Aula 08 - Utilizando Modulo
import math #Para importar um modulo especifico da biblioteca, é possivel utilizando o import {nome da biblioteca} from {o modulo escolhido}
num = int(input("Digite um numero: "))

raiz = math.sqrt(num)

print("A raiz de {}, é igual a {}".format(num, raiz))

